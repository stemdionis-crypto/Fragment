import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
Object.assign(globalThis, { localStorage: { getItem: () => null } });
const { idos, signalPackages, buySignalPackage } = await import('../client/src/idos');
const config = JSON.parse(readFileSync('idos/signal-pack.json', 'utf8'));
const offer = config.Offer;
assert.equal(Object.keys(config.Offers).length, 5);
for (const [frag, signals] of [[250,1],[125000,500],[250000,1000],[500000,2000],[1000000,4000]]) {
  const pack = config.Offers['fragment_signal_pack_'+signals];
  assert.deepEqual(pack.Pricing.Options.frag.Cost.Standard.Entries, [{ Type: 'CryptoCurrency', CurrencyID: 'Main', Amount: frag }]);
  assert.deepEqual(pack.Reward.Grant.Standard.Entries, [{ Type: 'VirtualCurrency', CurrencyID: 'SI', Amount: signals }]);
  assert.equal(config.Section.Slots[pack.OfferID].Rotation.OfferID, pack.OfferID);
  assert.equal(pack.Availability.Limits?.TotalCap, undefined);
}
assert.deepEqual(offer.Pricing.Options.frag.Cost.Standard.Entries, [{ Type: 'CryptoCurrency', CurrencyID: 'Main', Amount: 250000 }]);
assert.deepEqual(offer.Reward.Grant.Standard.Entries, [{ Type: 'VirtualCurrency', CurrencyID: 'SI', Amount: 1000 }]);
assert.equal(config.Section.Slots[offer.OfferID].Rotation.OfferID, offer.OfferID);
assert.equal(offer.Availability.Limits?.TotalCap, undefined, 'repeat purchases allowed');
const view = { OfferID: offer.OfferID, PriceOptions: [{ ...offer.Pricing.Options.frag }], Rewards: offer.Reward.Grant };
const front = { Stores: [{ StoreID: 'fragment', Sections: [{ SectionID: 'topups', Slots: [{ SlotID: offer.OfferID, Offer: view }] }] }] };
let reads = 0;
idos.store.getStorefront = async () => (++reads === 1 ? { ok: false, reason: 'throttled' } : { ok: true, data: front }) as any;
assert.equal((await signalPackages())[0].frag, 250000);
assert.equal(reads, 2, 'a throttled storefront read is retried once');
let charges = 0;
let release!: () => void;
idos.store.purchase = async (id, count, options) => {
  charges++;
  assert.equal(id, offer.OfferID); assert.equal(count, 1);
  assert.equal(options?.selectedOptionID, 'frag');
  assert.deepEqual(options?.slot, { storeID: 'fragment', sectionID: 'topups', slotID: offer.OfferID });
  await new Promise<void>(resolve => { release = resolve; });
  return { ok: true, data: {} } as any;
};
assert.equal((await signalPackages())[0].frag, 250000);
const first = buySignalPackage(offer.OfferID, 250000, 1000, () => {});
await new Promise(resolve => setTimeout(resolve, 0));
await buySignalPackage(offer.OfferID, 250000, 1000, () => {});
assert.equal(charges, 1, 'double submit must charge once'); release(); await first;
view.PriceOptions[0].Cost.Standard.Entries[0].Amount = 300000;
await assert.rejects(buySignalPackage(offer.OfferID, 250000, 1000, () => {}), /Package changed/);
assert.equal(charges, 1, 'changed price must not charge');
view.PriceOptions[0].Cost.Standard.Entries[0].Amount = 250000;
idos.store.purchase = async () => ({ ok: false, reason: 'server', error: 'insufficient' }) as any;
await assert.rejects(buySignalPackage(offer.OfferID, 250000, 1000, () => {}), /iDos: insufficient/);
console.log('Top-ups: approved price, correct resource types, repeat purchase, double-submit and price-change guards passed.');
