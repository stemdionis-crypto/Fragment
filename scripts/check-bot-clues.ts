import assert from 'node:assert/strict';
import { understandClue } from '../server/bot-lines';
assert.equal(understandClue('бурмалда',['key','lock']),null);
assert.equal(understandClue('чёрная птица, которая каркает',['owl','crow']), 'crow');
assert.equal(understandClue('зубчатое колесо',['circle','gear']), 'gear');
assert.equal(understandClue('то, чем открывают дверь',['key','lock']), 'key');
assert.equal(understandClue('то, чем открывают дверь или то, что задувают на торте',['key','candle']),null);
assert.equal(understandClue('пусто, как в кармане перед зарплатой',[0,1,2]),0);
assert.equal(understandClue('мурчит и просит кушать',['cat','owl','rabbit']), 'cat');
assert.equal(understandClue('мрулычет',['cat','owl','rabbit']), 'cat');
assert.equal(understandClue('рыбка в аквариуме',['cat','fish','owl']), 'fish');
assert.equal(understandClue('из нее чай пьют',['cup','bottle','knife']), 'cup');
assert.equal(understandClue('режет хлеб',['knife','key','book']), 'knife');
assert.equal(understandClue('шестерёнка',['circle','gear','clock']), 'gear');
assert.equal(understandClue('не колесо, а шестерня',['circle','gear']), 'gear');
assert.equal(understandClue('не ключ',['key','lock']), null);
assert.equal(understandClue('not a candle',['key','candle']), null);
assert.equal(understandClue('у собаки лапы',[1,2,3,4,5]),4);
assert.equal(understandClue('дни недели',[3,5,7,9]),7);
assert.equal(understandClue('медведи у Маши',[1,2,3,4]),3);
assert.equal(understandClue('a kitty that meows',['cat','owl','crow']), 'cat');
assert.equal(understandClue('a wheel with teeth',['circle','gear']), 'gear');
assert.equal(understandClue('cat or rabbit',['cat','rabbit']), null);
assert.equal(understandClue('катастрофа',['cat','owl']), null);
assert.equal(understandClue('я не знаю что тебе сказать',['cat']), null);
console.log('PASS: natural paraphrases, synonyms, typos, negation, numbers, ambiguity and unrelated words');
