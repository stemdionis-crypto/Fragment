type Case = [string, Value];
let failed = 0, total = 0;
function run(kind: TrialKind, options: Value[], cases: Case[], scale?: Glyph[]) {
  for (const [text, want] of cases) {
    total++;
    const got = understandFor(kind, text, options, scale);
    if (got !== want) { failed++; console.log(`FAIL ${kind}: "${text}" → ${got}, expected ${want}`); }
  }
}

