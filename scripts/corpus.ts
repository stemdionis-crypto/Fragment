export interface Case { kind: TrialKind; text: string; want: Value; scale?: Glyph[] }

let seed = 20261017;
const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296);
const pick = <T>(a: readonly T[]) => a[Math.floor(rnd() * a.length)];

const FILLER = ['', '', '', 'ну ', 'короче ', 'смотри, ', 'так, ', 'слушай, ', 'типа ', 'кароче ', 'значит ', 'вот '];
const NAME = ['', '', 'Эхо, ', 'ива ', 'Тень: ', 'эхо ', 'Ива, ', 'тень, '];
const TAIL = ['', '', '', '.', '!', ' вроде', ' кажется', ' ок?', ')', ' понял?', ' давай'];
const wrap = (core: string) => `${pick(FILLER)}${pick(NAME)}${core}${pick(TAIL)}`.replace(/\s+/g, ' ').trim();

// A light typo: swap two letters or drop one in a longer word, as people do when typing fast
function typo(text: string) {
  const words = text.split(' ');
  const i = words.findIndex((w) => w.length >= 6 && rnd() < 0.5);
  if (i < 0) return text;
  const w = words[i], j = 1 + Math.floor(rnd() * (w.length - 3));
  words[i] = rnd() < 0.5 ? w.slice(0, j) + w[j + 1] + w[j] + w.slice(j + 2) : w.slice(0, j) + w.slice(j + 1);
  return words.join(' ');
}

const out: Case[] = [];
const add = (kind: TrialKind, core: string, want: Value, scale?: Glyph[]) => {
  out.push({ kind, text: wrap(core), want, scale });
};

