// ---------- equalizer: bass / voice / treble, sticking out or lying flat ----------
const BAND = [['бас', 'басы', 'басовая'], ['голос', 'середина', 'средняя'], ['писк', 'тонкая', 'писклявая']];
const UPW = ['торчит', 'стоит', 'поднята', 'вверх торчит', 'столбом', 'высокая'], DOWNW = ['лежит', 'опущена', 'лежит плашмя', 'внизу', 'пустая', 'низкая'];
for (let i = 0; i < 180; i++) {
  const bits = [0, 1, 2].map(() => (rnd() < 0.5 ? 1 : 0));
  const v = (bits[0] << 2) | (bits[1] << 1) | bits[2];
  const style = rnd();
  let core: string;
  if (style < 0.5) core = [0, 1, 2].map((b) => `${pick(BAND[b])} ${pick(bits[b] ? UPW : DOWNW)}`).join(pick([', ', ' и ', '; ']));
  else if (style < 0.75 && bits.filter(Boolean).length === 1) core = `${pick(['торчит только', 'стоит только', 'поднята только'])} ${pick(BAND[bits.indexOf(1)])}`;
  else if (style < 0.75 && bits.filter(Boolean).length === 2) core = `${pick(['всё торчит кроме', 'все стоят кроме', 'все подняты кроме'])} ${pick(['баса', 'голоса', 'писка'][bits.indexOf(0)] ? [['баса', 'голоса', 'писка'][bits.indexOf(0)]] : [''])}`;
  else if (v === 7) core = pick(['все торчат', 'все подняты', 'всё стоит столбом']);
  else if (v === 0) core = pick(['все лежат', 'всё опущено', 'все пустые']);
  else core = [0, 1, 2].map((b) => `${pick(BAND[b])} ${pick(bits[b] ? UPW : DOWNW)}`).join(', ');
  add('equalizer', core, v);
}

// ---------- morse: sounds in order ----------
