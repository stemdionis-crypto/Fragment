import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
const directory = mkdtempSync(join(tmpdir(), 'fragment-bot-rating-'));
process.env.FRAGMENT_DATA_DIR = directory; delete process.env.DATABASE_URL; delete process.env.RENDER;
const e = await import('../server/economy');
try {
  const a = await e.identify(), guest = await e.identify();
  await e.bindWallet(a.id, 'test-rating-wallet');
  const b = await e.syncPlatform('rating-idos', { owned: ['classic'], items: [], equipped: 'classic', loadout: {} }, '0', true);
  assert.equal(e.profile(a.id).botPoints, 0);
  assert.equal(e.leaderboard('bots').length, 0);
  await Promise.all([e.recordMatch(a.id, 'bot-win', true, 120, 'Winner', true, true), e.recordMatch(a.id, 'bot-win', true, 120, 'Winner', true, true)]);
  assert.equal(e.profile(a.id).botPoints, 10); assert.equal(e.profile(a.id).botGamesPlayed, 1);
  await e.recordMatch(b.id, 'bot-loss', false, 10, 'Eliminated', true, true);
  assert.equal(e.profile(b.id).botPoints, 0);
  for (let n = 0; n < 3; n++) await e.recordMatch(guest.id, `guest-win-${n}`, true, 60, 'Hidden guest', true, true);
  assert.equal(e.profile(guest.id).botPoints, 30);
  await e.recordMatch(a.id, 'human-win', true, 60, 'Winner', false);
  await e.recordMatch(a.id, 'human-loss', false, 60, 'Winner', false);
  assert.equal(e.profile(a.id).botPoints, 10, 'human matches cannot change bot points');
  const ladder = e.leaderboard('bots');
  assert.deepEqual(ladder.map(row => row.value), [10, 0]);
  assert.deepEqual(ladder.map(row => row.name), ['Winner', 'Eliminated']);
  assert(!ladder.some(row => row.name === 'Hidden guest'), 'guest with more points must not enter the shared ranking');
  assert.equal(ladder[1].wallet, 'iDos', 'iDos-only profile can rank without a wallet');
  assert.equal(e.profile(a.id).balance, 0); assert.equal(e.profile(b.id).balance, 0);
  const saved = JSON.parse(readFileSync(join(directory, 'profiles.json'), 'utf8'));
  saved.find((account: { id: string }) => account.id === b.id).botPoints = -30;
  writeFileSync(join(directory, 'profiles.json'), JSON.stringify(saved));
  const child = spawnSync(process.execPath, ['--import', 'tsx', '--input-type=module', '-e', `
    import assert from 'node:assert/strict';
    const e = await import('./server/economy.ts');
    assert.deepEqual(e.leaderboard('bots').map(r => r.value), [10, 0]);
    const a = await e.identify(process.env.TEST_TOKEN);
    assert.equal(e.profile(a.id).botPoints, 10);
    await e.recordMatch(a.id, 'bot-win', true, 120, 'Winner', true, true);
    assert.equal(e.profile(a.id).botPoints, 10);
    await e.closeAccountStore();
  `], { env: { ...process.env, TEST_TOKEN: a.token }, encoding: 'utf8', timeout: 20_000 });
  assert.equal(child.status, 0, child.stderr);
  assert(JSON.parse(readFileSync(join(directory, 'profiles.json'), 'utf8')).every((account: { botPoints?: number }) => (account.botPoints ?? 0) >= 0), 'legacy negative scores must be corrected in storage');
  await e.recordMatch(a.id, 'bot-loss-a', false, 10, 'Winner', true, true);
  assert.equal(e.profile(a.id).botPoints, 0, 'a loss subtracts 10 from earned points');
  await e.recordMatch(a.id, 'bot-loss-b', false, 10, 'Winner', true, true);
  assert.equal(e.profile(a.id).botPoints, 0, 'repeat losses stay at zero');
  for (const metric of ['bots', 'speed', 'signal', 'games'] as const) assert(e.leaderboard(metric).every(row => row.value >= 0));
  console.log('PASS: zero floor, legacy negative migration, bot-only +10/-10, authenticated ranking, idempotency, no Signals or human-match points');
} finally { await e.closeAccountStore(); rmSync(directory, { recursive: true, force: true }); }
